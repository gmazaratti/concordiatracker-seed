export type ObT = (key: ObKey, vars?: Record<string, string | number>) => string

/** The flow's translator, following the app's language setting. */
export function useOb(): ObT {
  const { lang } = useI18n()
  return useCallback(
    (key, vars) => {
      const raw: string = (lang === 'fr' ? FR : EN)[key]
      return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : raw
    },
    [lang],
  )
}
